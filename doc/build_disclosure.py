def set_run_font(run, size=12, bold=None):
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts"); rpr.insert(0, rfonts)
    rfonts.set(qn("w:eastAsia"), "宋体")
    rfonts.set(qn("w:ascii"), "Times New Roman")
    rfonts.set(qn("w:hAnsi"), "Times New Roman")
    if bold is not None:
        run.bold = bold


def add_rich(par, text, size=12, bold=None):
    """按 _{} 和 ^{} 排下标和上标。"""
    for tok in re.split(r"([_^]\{[^}]*\})", text):
        if not tok:
            continue
        if tok[0] in "_^" and tok[1:2] == "{":
            r = par.add_run(tok[2:-1])
            r.font.subscript = tok[0] == "_"
            r.font.superscript = tok[0] == "^"
        else:
            r = par.add_run(tok)
        set_run_font(r, size, bold)


def fmt(par, indent=True, align=None):
    pf = par.paragraph_format
    pf.line_spacing = 1.5
    pf.space_before = Pt(0); pf.space_after = Pt(0)
    pf.first_line_indent = Pt(24) if indent else Pt(0)
    if align:
        par.alignment = align


def set_borders(table):
    tblPr = table._tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single"); el.set(qn("w:sz"), "4"); el.set(qn("w:color"), "000000")
        borders.append(el)
    tblPr.append(borders)


def fill(cell, body):
    # 去掉单元格里原有的空段落，第一段复用
    paras = list(cell.paragraphs)
    for p in paras[1:]:
        p._element.getparent().remove(p._element)
    first = [paras[0]]

    def new_par():
        return first.pop() if first else cell.add_paragraph()

    lines = [l for l in body.strip("\n").split("\n")]
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(lines[i].strip("|").split("|")); i += 1
            t = cell.add_table(rows=len(rows), cols=len(rows[0]))
            set_borders(t)
            for r, row in enumerate(rows):
                for c, val in enumerate(row):
                    p = t.cell(r, c).paragraphs[0]
                    fmt(p, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER)
                    p.paragraph_format.line_spacing = 1.2
                    add_rich(p, val, size=10.5, bold=(r == 0))
            continue
        p = new_par()
        if line.startswith("#"):
            fmt(p, indent=False); add_rich(p, line[1:], bold=True)
        elif line.startswith("="):
            fmt(p, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER)
            add_rich(p, re.sub(r"(?<=[^\[(,])([=+-])(?=[^{])", lambda m: " %s " % m.group(1).replace("-", "−"), line[1:]))
        elif line.startswith("@"):
            fmt(p, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER)
            p.paragraph_format.line_spacing = 1.0
            p.add_run().add_picture(os.path.join(FIGS, line[1:]), width=Cm(14))
        elif line.startswith("~"):
            fmt(p, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER); add_rich(p, line[1:], size=10.5)
        else:
            fmt(p); add_rich(p, line)
