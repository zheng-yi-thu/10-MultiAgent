def fill_after_title(cell, body):
    """第六栏只追加，不复用标题段落。"""
    class Wrap:
        def __init__(self, c):
            self.c = c
        @property
        def paragraphs(self):
            return self.c.paragraphs[1:]
        def add_paragraph(self):
            return self.c.add_paragraph()
        def add_table(self, rows, cols):
            return self.c.add_table(rows, cols)
    fill(Wrap(cell), body)


